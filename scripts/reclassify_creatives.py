"""Re-runs the classification contract (`cs.ingest.fivetran.classify.classify`) over
creatives already ingested under the old `else: image` default, and reports -- or,
with --apply, writes -- whatever changed.

Until this week, ingest labeled anything it could not prove was an image as
`format='image'`. Fixing that code (see cs.ingest.fivetran.classify) did not fix
rows synced under the old default: they still carry `format='image'`, their stored
`original_image` asset is actually a video preview frame, and their tags were
generated by the image model, from that one arbitrary frame, against the image
taxonomy -- invalid output, not merely mislabeled.

Two outcomes fall out of re-running classify(): image -> video (evidence proves a
video) and image -> unresolved (no rule proves anything). Both delete the
creative's tags/tag_run rows -- the "produced by
the image model from an unproven premise" argument holds for either verdict. Only
image -> video additionally clears primary_asset_id and deletes the stale asset (a
replacement download gets enqueued); image -> unresolved leaves its stale asset in
place and enqueues nothing, because 'unresolved' is a terminal state -- see
_apply_one and the dry-run report for exactly what that means for those rows.

Usage:
    uv run python scripts/reclassify_creatives.py --org <uuid>            # dry run (default)
    uv run python scripts/reclassify_creatives.py --org <uuid> --apply    # write changes

DRY RUN IS THE DEFAULT. Nothing in this module issues a mutating SQL statement or
calls queue.enqueue unless --apply is passed on the command line (or a caller
invokes apply_plan() directly) -- build_plan() only ever reads.

Blob-cleanup decision: deleted `asset` rows leave their blob object in place
(orphaned), not deleted. cs.core.blobs.BlobStore (Local/S3) exposes no delete
method at all today -- adding one, and wiring it in here, is a separate, riskier
change than this backfill needs, and an orphaned object costs storage, not
correctness or money on every run the way a bad tag or a paid re-tag would. This
script instead prints the `asset.path` of every row it deletes, one at a time as
each creative's deletion commits (not batched to the end of the run -- a crash
partway through must not lose the record of what was already orphaned), so an
operator can feed that list to a dedicated GC pass later, if one gets built.

`tag` (`tag.tag_run_id`) REFERENCES `tag_run(id)` with no `ON DELETE` clause, so tags
must be deleted before `tag_run` itself.
output, and nothing here invalidates it.
"""

from __future__ import annotations

import argparse
import asyncio
import logging
from collections import Counter
from dataclasses import dataclass, field
from uuid import UUID

from cs.core import queue
from cs.core.config import get_settings
from cs.core.db import Database
from cs.core.repo import get_meta_connection
from cs.ingest.fivetran.classify import Classification, classify, stored_verdict
from cs.ingest.fivetran.schema import AD_VIDEO_HISTORY, CREATIVE_HISTORY
from cs.ingest.fivetran.transform import (
    _afs_video_creative_ids,
    _feed_spec_image_urls,
    _full_watch_creative_ids,
    _impressions_by_creative,
    _latest_rows,
    _video_view_creative_ids,
)

log = logging.getLogger("scripts.reclassify_creatives")


def _pid(value: object) -> str | None:
    """Fivetran lands Meta's numeric ids as bigint; every id we join against is
    text. Mirrors cs.ingest.fivetran.transform._pid."""
    return None if value is None else str(value)


@dataclass
class ReclassifyRow:
    creative_id: UUID
    platform_creative_id: str
    impressions: int
    old_format: str
    old_source: str
    # What classify() proves, before the "image/video need their file" rule is applied.
    verdict_format: str
    verdict_source: str
    asset_url: str | None
    primary_asset_kind: str | None = None

    @property
    def is_image_to_video(self) -> bool:
        return self.old_format == "image" and self.verdict_format == "video"

    @property
    def is_image_to_unresolved(self) -> bool:
        return self.old_format == "image" and self.verdict_format == "unresolved"

    @property
    def needs_image_download(self) -> bool:
        """The verdict is an image whose file we don't have yet: a new image, or one
        whose stored file came from the cropped thumbnail and now has a feed-spec image.
        An image_url verdict already has its file -- classify() always preferred it."""
        if self.verdict_format != "image" or not self.asset_url:
            return False
        feed_image = "asset_feed_spec_image"
        return self.primary_asset_kind != "original_image" or (
            self.old_format == "image"
            and self.verdict_source == feed_image
            and self.old_source != feed_image
        )

    @property
    def _stored(self) -> tuple[str, str]:
        # A file this run deletes doesn't count toward keeping the label.
        replaced = self.needs_image_download or self.is_image_to_video
        kind = None if replaced else self.primary_asset_kind
        return stored_verdict(Classification(self.verdict_format, self.verdict_source), kind)

    @property
    def new_format(self) -> str:
        return self._stored[0]

    @property
    def new_source(self) -> str:
        return self._stored[1]

    @property
    def changed(self) -> bool:
        return (self.old_format, self.old_source) != (self.new_format, self.new_source) or (
            self.needs_image_download
        )


@dataclass
class ReclassifyPlan:
    org_id: UUID
    rows: list[ReclassifyRow] = field(default_factory=list)
    # App creative rows (with ads) whose platform_creative_id has no matching
    # Fivetran creative_history row -- e.g. the landed row aged out, or the id
    # was never in this schema. Left untouched; nothing to reclassify against.
    missing_from_fivetran: int = 0
    # Fivetran creative_history rows with no matching app `creative` row --
    # not yet ingested (or belonging to a still-paused account). Not this
    # script's concern: a normal sync run picks these up with the fixed
    # classifier already, they were never mislabeled by the app.
    fivetran_only: int = 0
    # App creatives in this org with zero `ad` rows -- excluded from `rows`
    # entirely (so the AFTER tally stays comparable to the design's "creatives
    # with ads" validation table), but left untouched by this script. If any
    # of these still carry format_source='legacy_guess', a later
    # `GROUP BY format_source` audit will show it and this is why.
    no_ads: int = 0

    @property
    def changed(self) -> list[ReclassifyRow]:
        return [r for r in self.rows if r.changed]

    def before_tally(self) -> Counter:
        return Counter((r.old_format, r.old_source) for r in self.rows)

    def after_tally(self) -> Counter:
        return Counter((r.new_format, r.new_source) for r in self.rows)

    def transition_tally(self) -> Counter:
        return Counter(
            (r.old_format, r.old_source, r.new_format, r.new_source) for r in self.changed
        )


@dataclass
class ApplyResult:
    # Blob paths behind deleted asset rows -- orphaned, not removed from blob
    # storage. See module docstring.
    orphaned_asset_paths: list[str] = field(default_factory=list)
    # Creatives whose transaction raised and were skipped, not aborting the
    # rest of the (impression-ordered) run. See log output for creative_id
    # and the exception for each.
    failed: int = 0


async def build_plan(db: Database, org_id: UUID) -> ReclassifyPlan:
    """Read-only. Re-runs classify() over every Fivetran creative_history row
    matched to an app `creative` row that has at least one ad, in descending
    impression order, and returns what would change. Never mutates."""
    conn = await get_meta_connection(db, org_id)
    if conn is None:
        raise SystemExit(f"no meta_connection found for org {org_id}")
    schema = conn["schema_name"]

    videos_by_id = {
        pid: r["source"]
        for r in await _latest_rows(db, schema, AD_VIDEO_HISTORY)
        if r["source"] and (pid := _pid(r["id"])) is not None
    }
    afs_ids = await _afs_video_creative_ids(db, schema)
    vv_ids = await _video_view_creative_ids(db, schema)
    impressions = await _impressions_by_creative(db, schema)
    feed_spec_images = await _feed_spec_image_urls(db, schema)
    full_watches = await _full_watch_creative_ids(db, schema)

    fivetran_by_pid = {
        pid: r
        for r in await _latest_rows(db, schema, CREATIVE_HISTORY)
        if (pid := _pid(r["id"])) is not None
    }

    # Driven from the app's own `creative` + `metric_daily`, not Fivetran's
    # creative_history: impression volume (the ordering key) and "has this
    # creative ever served an ad" (the "creatives with ads" filter the design's
    # validation table uses) both live only in our own schema.
    app_rows = await db.fetch(
        """
        SELECT c.id, c.platform_creative_id, c.format, c.format_source,
               COALESCE(m.impressions, 0) AS impressions, pa.kind AS primary_asset_kind
        FROM creative c
        LEFT JOIN asset pa ON pa.id = c.primary_asset_id
        LEFT JOIN (
            SELECT creative_id, sum(impressions) AS impressions
            FROM metric_daily WHERE org_id = $1 GROUP BY creative_id
        ) m ON m.creative_id = c.id
        WHERE c.org_id = $1 AND EXISTS (SELECT 1 FROM ad a WHERE a.creative_id = c.id)
        ORDER BY impressions DESC, c.id
        """,
        org_id,
    )
    no_ads = await db.fetchval(
        """
        SELECT count(*) FROM creative c
        WHERE c.org_id = $1 AND NOT EXISTS (SELECT 1 FROM ad a WHERE a.creative_id = c.id)
        """,
        org_id,
    )

    plan = ReclassifyPlan(org_id=org_id, no_ads=no_ads or 0)
    matched_pids: set[str] = set()
    for row in app_rows:
        fr = fivetran_by_pid.get(row["platform_creative_id"])
        if fr is None:
            plan.missing_from_fivetran += 1
            continue
        matched_pids.add(row["platform_creative_id"])
        verdict = classify(
            fr,
            videos_by_id=videos_by_id,
            afs_video_creative_ids=afs_ids,
            video_view_creative_ids=vv_ids,
            impressions_by_creative_id=impressions,
            feed_spec_image_urls=feed_spec_images,
            full_watch_creative_ids=full_watches,
        )
        plan.rows.append(
            ReclassifyRow(
                creative_id=row["id"],
                platform_creative_id=row["platform_creative_id"],
                impressions=row["impressions"] or 0,
                old_format=row["format"],
                old_source=row["format_source"],
                verdict_format=verdict.format,
                verdict_source=verdict.source,
                asset_url=verdict.asset_url,
                primary_asset_kind=row["primary_asset_kind"],
            )
        )
    plan.fivetran_only = len(fivetran_by_pid) - len(matched_pids)
    return plan


async def _apply_one(db: Database, org_id: UUID, row: ReclassifyRow) -> list[str]:
    """Writes one changed verdict inside a single transaction. Returns the blob
    paths of any asset rows it deleted. Raises on failure -- the caller decides
    whether to isolate that from the rest of the run."""
    orphaned: list[str] = []
    async with db.transaction() as tx:
        await tx.execute(
            "UPDATE creative SET format=$2, format_source=$3, "
            "format_verified_at = CASE WHEN $2 = 'unresolved' THEN NULL ELSE now() END "
            "WHERE id=$1",
            row.creative_id,
            row.new_format,
            row.new_source,
        )
        if row.needs_image_download:
            return await _replace_with_image_download(tx, org_id, row)
        if not (row.is_image_to_video or row.is_image_to_unresolved):
            return orphaned
        # Every tag on this creative was produced by the image model, against the image
        # taxonomy, from a premise -- "this creative is provably an image" -- that no
        # longer holds for either transition: invalid output, not merely stale, and must
        # go together with the format correction, not in a later pass. This applies
        # verbatim to image -> unresolved: we are asserting we can no longer prove the
        # format at all, a strictly weaker claim than "this is a video", so the tags are
        # equally unproven. Delete in FK order regardless of which transition this is.
        if row.is_image_to_video:
            # The stored asset is a video preview frame the old bug picked more or less
            # arbitrarily -- delete it. image -> unresolved instead LEAVES its stale
            # asset and primary_asset_id in place (see module docstring / Task 4 of the
            # final review this commit implements): we can no longer prove this creative
            # is a video either, so there is nothing to replace the asset with.
            stale = await tx.fetch(
                "SELECT path FROM asset WHERE org_id=$1 AND creative_id=$2"
                " AND kind='original_image'",
                org_id,
                row.creative_id,
            )
            orphaned = [r["path"] for r in stale]
            await tx.execute(
                "UPDATE creative SET primary_asset_id=NULL WHERE id=$1", row.creative_id
            )
            await tx.execute(
                "DELETE FROM asset WHERE org_id=$1 AND creative_id=$2 AND kind='original_image'",
                org_id,
                row.creative_id,
            )
        # tag references tag_run with no ON DELETE clause, so tags go first.
        await tx.execute("DELETE FROM tag WHERE creative_id=$1", row.creative_id)
        # The insight paragraph was written against the wrong format too.
        await tx.execute("DELETE FROM creative_insight WHERE creative_id=$1", row.creative_id)
        await tx.execute("DELETE FROM tag_run WHERE creative_id=$1", row.creative_id)
        if row.is_image_to_video and row.asset_url:
            await queue.enqueue(
                tx,
                org_id,
                "meta.download_creative",
                {
                    "creative_id": str(row.creative_id),
                    "asset_url": row.asset_url,
                    "kind": "original_video",
                    "format": row.verdict_format,
                    "format_source": row.verdict_source,
                },
                # Shares the normal sync path's dedup namespace
                # (transform.py's meta.download_creative enqueue uses
                # dedup_key=str(creative_id)) so a concurrent sync can't
                # double-enqueue the same download under a different key.
                dedup_key=str(row.creative_id),
            )
        # image -> unresolved gets no enqueue of any kind: 'unresolved' blocks both
        # re-tagging and re-download (see the tagging-guard and sync-path checks
        # elsewhere in this codebase), so there is nothing safe to schedule here.
    return orphaned


async def _replace_with_image_download(tx, org_id: UUID, row: ReclassifyRow) -> list[str]:
    """Inside _apply_one's transaction: drop the stored file (a thumbnail crop, or a
    video/none for a creative that just became an image) and every tag made from it,
    then queue the full-size image. The download re-queues tagging when it lands."""
    stale = await tx.fetch(
        "SELECT path FROM asset WHERE org_id=$1 AND creative_id=$2"
        " AND kind IN ('original_image', 'original_video')",
        org_id,
        row.creative_id,
    )
    await tx.execute("UPDATE creative SET primary_asset_id=NULL WHERE id=$1", row.creative_id)
    await tx.execute(
        "DELETE FROM asset WHERE org_id=$1 AND creative_id=$2"
        " AND kind IN ('original_image', 'original_video')",
        org_id,
        row.creative_id,
    )
    # tag references tag_run with no ON DELETE clause, so tags go first.
    await tx.execute("DELETE FROM tag WHERE creative_id=$1", row.creative_id)
    await tx.execute("DELETE FROM creative_insight WHERE creative_id=$1", row.creative_id)
    await tx.execute("DELETE FROM tag_run WHERE creative_id=$1", row.creative_id)
    await queue.enqueue(
        tx,
        org_id,
        "meta.download_creative",
        {
            "creative_id": str(row.creative_id),
            "asset_url": row.asset_url,
            "kind": "original_image",
            "format": row.verdict_format,
            "format_source": row.verdict_source,
        },
        dedup_key=str(row.creative_id),
    )
    return [r["path"] for r in stale]


async def apply_plan(db: Database, org_id: UUID, plan: ReclassifyPlan) -> ApplyResult:
    """Writes every changed verdict in `plan`, one creative at a time.

    Only ever called when --apply is passed; the caller (`run`, below) is the
    single gate. Each creative's writes happen inside one transaction so a
    creative is never left with a new format but stale tags, or vice versa. A
    failure on one creative is logged and counted, not allowed to abort the
    rest of the (impression-ordered) run -- mirrors the per-row fault
    isolation in cs.ingest.fivetran.transform._sync_ads_and_creatives."""
    result = ApplyResult()
    for row in plan.changed:
        try:
            orphaned = await _apply_one(db, org_id, row)
        except Exception:
            result.failed += 1
            log.exception(
                "failed to apply reclassification for creative",
                extra={"org_id": str(org_id), "creative_id": str(row.creative_id)},
            )
            continue
        for path in orphaned:
            # Printed as each creative commits, not batched to the end: a
            # crash later in the run must not lose the record of what's
            # already orphaned.
            print(f"  orphaned (not deleted): {path}  (creative {row.creative_id})")
        result.orphaned_asset_paths.extend(orphaned)
    return result


def _print_report(plan: ReclassifyPlan) -> None:
    print(
        f"org {plan.org_id}: {len(plan.rows)} creative(s) with ads matched to Fivetran, "
        f"processed in descending impression order"
    )
    if plan.no_ads:
        print(
            f"  {plan.no_ads} app creative(s) have no `ad` row at all -- excluded from "
            f"everything below (including the AFTER tally, to stay comparable to the "
            f"design's validation table) and left untouched. If any still carry "
            f"format_source='legacy_guess' after --apply, this is why."
        )
    if plan.missing_from_fivetran:
        print(
            f"  {plan.missing_from_fivetran} app creative(s) with ads have no matching "
            f"Fivetran creative_history row -- left untouched"
        )
    if plan.fivetran_only:
        print(
            f"  {plan.fivetran_only} Fivetran creative_history row(s) have no matching "
            f"app creative -- not mislabeled by us yet, a normal sync will classify them "
            f"correctly on ingest"
        )

    print("\nBEFORE (stored format / format_source):")
    for (fmt, src), n in plan.before_tally().most_common():
        print(f"  {n:6d}  {fmt:<12s} {src}")

    print("\nAFTER (re-run classify()) -- compare against the design's validation table:")
    for (fmt, src), n in plan.after_tally().most_common():
        print(f"  {n:6d}  {fmt:<12s} {src}")

    changed = plan.changed
    print(f"\n{len(changed)} creative(s) would change verdict:")
    for (of, osrc, nf, nsrc), n in plan.transition_tally().most_common():
        print(f"  {n:6d}  {of}/{osrc}  ->  {nf}/{nsrc}")

    i2v = [r for r in changed if r.is_image_to_video]
    if i2v:
        with_url = [r for r in i2v if r.asset_url]
        without_url = [r for r in i2v if not r.asset_url]
        print(
            f"\n{len(i2v)} of those are image -> video: primary_asset_id cleared, the stale "
            f"original_image asset row deleted (blob object orphaned, not removed -- see "
            f"module docstring), and tag/tag_run rows "
            f"deleted for all of them (those tags were produced by the image model from a "
            f"video frame and are invalid regardless of whether a replacement is available)."
        )
        print(f"  {len(with_url):6d}  will be re-downloaded (and re-tagged once that lands)")
        if without_url:
            print(
                f"  {len(without_url):6d}  *** will be left with NO asset and NO tags -- "
                f"classify() found no downloadable URL for these, so nothing is enqueued. "
                f"They stay untagged until a separate resolution path (Apify/Instagram, or "
                f"a future sync landing ad_video_history) gives them one. ***"
            )

    downloads = [r for r in changed if r.needs_image_download]
    if downloads:
        print(
            f"\n{len(downloads)} of those get a full-size image file: any stored file (a cropped "
            f"thumbnail, or none) and its tags are deleted, and the image download is queued "
            f"(tagging re-runs when it lands)."
        )
        for (of, osrc, nf, nsrc), n in Counter(
            (r.old_format, r.old_source, r.new_format, r.new_source) for r in downloads
        ).most_common():
            print(f"  {n:6d}  {of}/{osrc}  ->  {nf}/{nsrc}")
    no_file = [
        r
        for r in changed
        if r.verdict_format in ("image", "video")
        and r.new_format == "unresolved"
        and not r.needs_image_download
        and not (r.is_image_to_video and r.asset_url)
    ]
    if no_file:
        print(
            f"\n{len(no_file)} proven image/video creative(s) have no file we can fetch: "
            f"stored unresolved until a sync or resolve job lands one."
        )

    i2u = [r for r in changed if r.is_image_to_unresolved]
    if i2u:
        print(
            f"\n*** {len(i2u)} of those are image -> unresolved: for symmetry with "
            f"image -> video, their tag/tag_run rows "
            f"are DELETED (produced by the image model from a premise -- 'provably an "
            f"image' -- that no longer holds, so they are invalid output, not merely "
            f"stale). Their stale original_image asset and primary_asset_id are LEFT IN "
            f"PLACE (there is nothing to replace them with) and NOTHING is re-enqueued. "
            f"THESE {len(i2u)} CREATIVES END UP WITH NO TAGS, A STALE ASSET, AND NO PATH "
            f"TO REGAIN TAGS: format='unresolved' is a TERMINAL STATE that blocks both "
            f"re-tagging and re-download, permanently, for these rows. ***"
        )


async def run(org_id: UUID, apply: bool) -> ReclassifyPlan:
    settings = get_settings()
    db = await Database.connect(settings.database_url)
    try:
        plan = await build_plan(db, org_id)
        _print_report(plan)
        if apply:
            print()
            result = await apply_plan(db, org_id, plan)
            print(
                f"\napplied. {len(result.orphaned_asset_paths)} blob object(s) now orphaned "
                f"(listed above as they were deleted)."
            )
            if result.failed:
                print(
                    f"{result.failed} creative(s) FAILED and were skipped -- see logs for "
                    f"creative_id and exception. Re-running --apply is safe (already-fixed "
                    f"rows have nothing left to change) and will retry them."
                )
        else:
            print("\nDRY RUN -- pass --apply to write these changes.")
        return plan
    finally:
        await db.close()


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--org", required=True, help="org UUID")
    p.add_argument(
        "--apply", action="store_true", help="write changes (default: dry run, no writes)"
    )
    args = p.parse_args()
    asyncio.run(run(UUID(args.org), args.apply))


if __name__ == "__main__":
    main()
