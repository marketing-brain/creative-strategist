"""Re-runs the classification contract (`cs.ingest.fivetran.classify.classify`) over
creatives already ingested under the old `else: image` default, and reports -- or,
with --apply, writes -- whatever changed.

Until this week, ingest labeled anything it could not prove was an image as
`format='image'`. Fixing that code (see cs.ingest.fivetran.classify) did not fix
rows synced under the old default: they still carry `format='image'`, their stored
`original_image` asset is actually a video preview frame, and their tags were
generated by the image model, from that one arbitrary frame, against the image
taxonomy -- invalid output, not merely mislabeled.

Usage:
    uv run python scripts/reclassify_creatives.py --org <uuid>            # dry run (default)
    uv run python scripts/reclassify_creatives.py --org <uuid> --apply    # write changes

DRY RUN IS THE DEFAULT. Nothing in this module issues a mutating SQL statement or
calls queue.enqueue unless --apply is passed on the command line (or a caller
invokes apply_plan() directly) -- build_plan() only ever reads.

Blob-cleanup decision: deleted `asset` rows leave their blob object in place
(orphaned), not deleted. cs.core.blobs.BlobStore (Local/S3) exposes no delete
method at all today -- adding one, and wiring it in here, is a separate, riskier
change than this backfill needs, and an orphaned object costs storage, not
correctness or money on every run the way a bad tag or a paid re-tag would. This
script instead prints the `asset.path` of every row it deletes so an operator can
feed that list to a dedicated GC pass later, if one gets built.
"""

from __future__ import annotations

import argparse
import asyncio
from collections import Counter
from dataclasses import dataclass, field
from uuid import UUID

from cs.core import queue
from cs.core.config import get_settings
from cs.core.db import Database
from cs.core.repo import get_meta_connection
from cs.ingest.fivetran.classify import classify
from cs.ingest.fivetran.schema import AD_VIDEO_HISTORY, CREATIVE_HISTORY
from cs.ingest.fivetran.transform import (
    _afs_video_creative_ids,
    _latest_rows,
    _video_view_creative_ids,
)


def _pid(value: object) -> str | None:
    """Fivetran lands Meta's numeric ids as bigint; every id we join against is
    text. Mirrors cs.ingest.fivetran.transform._pid."""
    return None if value is None else str(value)


@dataclass
class ReclassifyRow:
    creative_id: UUID
    platform_creative_id: str
    impressions: int
    old_format: str
    old_source: str
    new_format: str
    new_source: str
    asset_url: str | None

    @property
    def changed(self) -> bool:
        return (self.old_format, self.old_source) != (self.new_format, self.new_source)

    @property
    def is_image_to_video(self) -> bool:
        return self.old_format == "image" and self.new_format == "video"


@dataclass
class ReclassifyPlan:
    org_id: UUID
    rows: list[ReclassifyRow] = field(default_factory=list)
    # App creative rows (with ads) whose platform_creative_id has no matching
    # Fivetran creative_history row -- e.g. the landed row aged out, or the id
    # was never in this schema. Left untouched; nothing to reclassify against.
    missing_from_fivetran: int = 0
    # Fivetran creative_history rows with no matching app `creative` row --
    # not yet ingested (or belonging to a still-paused account). Not this
    # script's concern: a normal sync run picks these up with the fixed
    # classifier already, they were never mislabeled by the app.
    fivetran_only: int = 0

    @property
    def changed(self) -> list[ReclassifyRow]:
        return [r for r in self.rows if r.changed]

    def before_tally(self) -> Counter:
        return Counter((r.old_format, r.old_source) for r in self.rows)

    def after_tally(self) -> Counter:
        return Counter((r.new_format, r.new_source) for r in self.rows)

    def transition_tally(self) -> Counter:
        return Counter(
            (r.old_format, r.old_source, r.new_format, r.new_source) for r in self.changed
        )


async def build_plan(db: Database, org_id: UUID) -> ReclassifyPlan:
    """Read-only. Re-runs classify() over every Fivetran creative_history row
    matched to an app `creative` row that has at least one ad, in descending
    impression order, and returns what would change. Never mutates."""
    conn = await get_meta_connection(db, org_id)
    if conn is None:
        raise SystemExit(f"no meta_connection found for org {org_id}")
    schema = conn["schema_name"]

    videos_by_id = {
        pid: r["source"]
        for r in await _latest_rows(db, schema, AD_VIDEO_HISTORY)
        if r["source"] and (pid := _pid(r["id"])) is not None
    }
    afs_ids = await _afs_video_creative_ids(db, schema)
    vv_ids = await _video_view_creative_ids(db, schema)

    fivetran_by_pid = {
        pid: r
        for r in await _latest_rows(db, schema, CREATIVE_HISTORY)
        if (pid := _pid(r["id"])) is not None
    }

    # Driven from the app's own `creative` + `metric_daily`, not Fivetran's
    # creative_history: impression volume (the ordering key) and "has this
    # creative ever served an ad" (the "creatives with ads" filter the design's
    # validation table uses) both live only in our own schema.
    app_rows = await db.fetch(
        """
        SELECT c.id, c.platform_creative_id, c.format, c.format_source,
               COALESCE(m.impressions, 0) AS impressions
        FROM creative c
        LEFT JOIN (
            SELECT creative_id, sum(impressions) AS impressions
            FROM metric_daily WHERE org_id = $1 GROUP BY creative_id
        ) m ON m.creative_id = c.id
        WHERE c.org_id = $1 AND EXISTS (SELECT 1 FROM ad a WHERE a.creative_id = c.id)
        ORDER BY impressions DESC, c.id
        """,
        org_id,
    )

    plan = ReclassifyPlan(org_id=org_id)
    matched_pids: set[str] = set()
    for row in app_rows:
        fr = fivetran_by_pid.get(row["platform_creative_id"])
        if fr is None:
            plan.missing_from_fivetran += 1
            continue
        matched_pids.add(row["platform_creative_id"])
        verdict = classify(
            fr,
            videos_by_id=videos_by_id,
            afs_video_creative_ids=afs_ids,
            video_view_creative_ids=vv_ids,
        )
        plan.rows.append(
            ReclassifyRow(
                creative_id=row["id"],
                platform_creative_id=row["platform_creative_id"],
                impressions=row["impressions"] or 0,
                old_format=row["format"],
                old_source=row["format_source"],
                new_format=verdict.format,
                new_source=verdict.source,
                asset_url=verdict.asset_url,
            )
        )
    plan.fivetran_only = len(fivetran_by_pid) - len(matched_pids)
    return plan


async def apply_plan(db: Database, org_id: UUID, plan: ReclassifyPlan) -> list[str]:
    """Writes every changed verdict in `plan`. Returns the blob paths of asset rows
    it deleted (orphaned, not removed from blob storage -- see module docstring).

    Only ever called when --apply is passed; the caller (`run`, below) is the
    single gate. Each creative's writes happen inside one transaction so a
    creative is never left with a new format but stale tags, or vice versa."""
    orphaned_asset_paths: list[str] = []
    for row in plan.changed:
        async with db.transaction() as tx:
            await tx.execute(
                "UPDATE creative SET format=$2, format_source=$3, "
                "format_verified_at = CASE WHEN $2 = 'unresolved' THEN NULL ELSE now() END "
                "WHERE id=$1",
                row.creative_id,
                row.new_format,
                row.new_source,
            )
            if not row.is_image_to_video:
                continue
            # The stored asset is a video preview frame the old bug picked more
            # or less arbitrarily, and every tag on this creative was produced
            # by the image model, against the image taxonomy, from that one
            # frame -- both are invalid output, not merely stale, and must go
            # together with the format correction, not in a later pass.
            stale = await tx.fetch(
                "SELECT path FROM asset WHERE org_id=$1 AND creative_id=$2"
                " AND kind='original_image'",
                org_id,
                row.creative_id,
            )
            orphaned_asset_paths.extend(r["path"] for r in stale)
            await tx.execute(
                "UPDATE creative SET primary_asset_id=NULL WHERE id=$1", row.creative_id
            )
            await tx.execute(
                "DELETE FROM asset WHERE org_id=$1 AND creative_id=$2 AND kind='original_image'",
                org_id,
                row.creative_id,
            )
            # FK order: creative_embedding and tag both reference tag_run with no
            # ON DELETE clause, so both must go before tag_run.
            await tx.execute(
                "DELETE FROM creative_embedding WHERE creative_id=$1", row.creative_id
            )
            await tx.execute("DELETE FROM tag WHERE creative_id=$1", row.creative_id)
            await tx.execute("DELETE FROM tag_run WHERE creative_id=$1", row.creative_id)
            if row.asset_url:
                await queue.enqueue(
                    tx,
                    org_id,
                    "meta.download_creative",
                    {
                        "creative_id": str(row.creative_id),
                        "asset_url": row.asset_url,
                        "kind": "original_video",
                    },
                    dedup_key=f"reclassify:{row.creative_id}",
                )
    return orphaned_asset_paths


def _print_report(plan: ReclassifyPlan) -> None:
    print(
        f"org {plan.org_id}: {len(plan.rows)} creative(s) with ads matched to Fivetran, "
        f"processed in descending impression order"
    )
    if plan.missing_from_fivetran:
        print(
            f"  {plan.missing_from_fivetran} app creative(s) with ads have no matching "
            f"Fivetran creative_history row -- left untouched"
        )
    if plan.fivetran_only:
        print(
            f"  {plan.fivetran_only} Fivetran creative_history row(s) have no matching "
            f"app creative -- not mislabeled by us yet, a normal sync will classify them "
            f"correctly on ingest"
        )

    print("\nBEFORE (stored format / format_source):")
    for (fmt, src), n in plan.before_tally().most_common():
        print(f"  {n:6d}  {fmt:<12s} {src}")

    print("\nAFTER (re-run classify()) -- compare against the design's validation table:")
    for (fmt, src), n in plan.after_tally().most_common():
        print(f"  {n:6d}  {fmt:<12s} {src}")

    changed = plan.changed
    print(f"\n{len(changed)} creative(s) would change verdict:")
    for (of, osrc, nf, nsrc), n in plan.transition_tally().most_common():
        print(f"  {n:6d}  {of}/{osrc}  ->  {nf}/{nsrc}")

    n_i2v = sum(1 for r in changed if r.is_image_to_video)
    if n_i2v:
        print(
            f"\n{n_i2v} of those are image -> video: primary_asset_id will be cleared, the "
            f"stale original_image asset row deleted (blob object orphaned, not removed -- "
            f"see module docstring), tag/tag_run/creative_embedding rows deleted, and "
            f"meta.download_creative (kind=original_video) enqueued where an asset URL is "
            f"known."
        )


async def run(org_id: UUID, apply: bool) -> ReclassifyPlan:
    settings = get_settings()
    db = await Database.connect(settings.database_url)
    try:
        plan = await build_plan(db, org_id)
        _print_report(plan)
        if apply:
            orphaned = await apply_plan(db, org_id, plan)
            print(f"\napplied. {len(orphaned)} blob object(s) now orphaned:")
            for path in orphaned:
                print(f"  {path}")
        else:
            print("\nDRY RUN -- pass --apply to write these changes.")
        return plan
    finally:
        await db.close()


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--org", required=True, help="org UUID")
    p.add_argument(
        "--apply", action="store_true", help="write changes (default: dry run, no writes)"
    )
    args = p.parse_args()
    asyncio.run(run(UUID(args.org), args.apply))


if __name__ == "__main__":
    main()
